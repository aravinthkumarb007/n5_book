const isKanjiChar = (c: string) => /[\u4E00-\u9FAF\u3005]/.test(c);
const compoundKeysSorted = Object.keys(COMPOUND_WORD_BREAKDOWN).sort((a, b) => b.length - a.length);

export interface SentenceToken {
  text: string;
  isKanji: boolean;
  reading?: string;
}

export function tokenizeSentence(japanese: string): SentenceToken[] {
  const tokens: SentenceToken[] = [];
  let idx = 0;

  while (idx < japanese.length) {
    // 1. Try compound words breakdown
    let matched = false;
    for (const word of compoundKeysSorted) {
      if (japanese.startsWith(word, idx)) {
        matched = true;
        const breakdown = COMPOUND_WORD_BREAKDOWN[word];
        for (const [char, reading] of breakdown) {
          const charHasKanji = isKanjiChar(char);
          tokens.push({
            text: char,
            isKanji: charHasKanji,
            reading: charHasKanji ? reading : undefined
          });
        }
        idx += word.length;
        break;
      }
    }
    if (matched) continue;

    // 2. Try standalone kanji
    const currentChar = japanese[idx];
    if (isKanjiChar(currentChar)) {
      tokens.push({
        text: currentChar,
        isKanji: true,
        reading: STANDALONE_KANJI_DICT[currentChar] || currentChar
      });
      idx++;
      continue;
    }

    // 3. Non-kanji run (hiragana, katakana, punctuation, latin)
    let nonKanjiRun = '';
    while (idx < japanese.length && !isKanjiChar(japanese[idx])) {
      nonKanjiRun += japanese[idx];
      idx++;
    }
    tokens.push({
      text: nonKanjiRun,
      isKanji: false
    });
  }

  return tokens;
}

/**
 * Filters a Japanese example sentence so that ONLY kanji the user has
 * completed/learned are displayed as kanji. All other kanji are replaced
 * with their natural hiragana reading.
 *
 * If completedKanjiSet is empty, the entire sentence is displayed in kana.
 */
export function filterSentenceByCompletedKanji(
  japanese: string,
  hiraganaWithSpaces: string,
  completedKanjiSet: Set<string>
): string {
  // Rule 8: If the user has not completed any kanji, display entirely in kana
  if (completedKanjiSet.size === 0) {
    const tokens = tokenizeSentence(japanese);
    return tokens.map(t => (t.isKanji ? (t.reading || t.text) : t.text)).join('');
  }

  const tokens = tokenizeSentence(japanese);
  return tokens.map(t => {
    if (!t.isKanji) return t.text;

    // Multi-kanji ateji unit like '今日' or '明日'
    if (t.text.length > 1) {
      const allCharsCompleted = t.text.split('').every(c => !isKanjiChar(c) || completedKanjiSet.has(c));
      return allCharsCompleted ? t.text : (t.reading || t.text);
    }

    // Single kanji character
    if (completedKanjiSet.has(t.text)) {
      return t.text;
    }
    return t.reading || t.text;
  }).join('');
}

/**
 * Retrieves the set of Kanji characters that the user has completed/studied
 * based on the database and storage progress records.
 */
export function getCompletedKanjiSet(): Set<string> {
  const progressList = storage.getProgress();
  const completedSet = new Set<string>();

  for (const p of progressList) {
    if (
      p.learning_status === 'learned' ||
      p.learning_status === 'needs_revision' ||
      Boolean(p.learned_at)
    ) {
      const kanjiMeta = ALL_120_KANJI.find(k => k.id === p.kanji_id);
      if (kanjiMeta) {
        completedSet.add(kanjiMeta.character);
      }
    }
  }

  return completedSet;
}

